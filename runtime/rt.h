/* Runtime for the recompiled N.O.V.A. 3 library: game memory, imports, threads, JNI.
 *
 * Game memory is one 4 GB reservation; a game address is an offset into it (rt_mem). The translated code
 * (tools/recomp/lift.py) calls rc_import for the library's imports and rc_dispatch for computed targets;
 * rc_dispatch sends addresses in the host-function range to rc_hostcall, which is how game code calls
 * runtime functions through pointers (JNI function tables, OpenSL interfaces, thread entry returns).
 */
#ifndef NOVA_RT_H
#define NOVA_RT_H

#include <stdarg.h>
#include <stddef.h>
#include <stdint.h>

#include "recomp.h"

/* ---- game memory layout ---------------------------------------------------------------------- */
#define RT_HOSTFN_BASE 0x00e00000u  /* host functions: 4 bytes per slot */
#define RT_HOSTFN_MAX 0x10000u
#define RT_DATAIMP_BASE 0x00e80000u /* data imports (__sF, _ctype_, ...) */
#define RT_DATAIMP_SIZE 0x10000u
#define RT_HEAP_BASE 0x02000000u    /* game heap, thread stacks and TLS blocks */
#define RT_HEAP_END 0x60000000u
#define RT_RETURN_SENTINEL (RT_HOSTFN_BASE) /* hostfn slot 0: a guest call made from the runtime returns here */

typedef struct { const char *name; uint32_t addr; } rt_named_addr;

/* image_meta.c (generated by tools/recomp/pack_image.py) */
extern const uint32_t rt_image_base, rt_image_size, rt_import_stub_base;
extern const uint32_t rt_init_array[], rt_init_array_count;
extern const char *const rt_import_names[];
extern const uint32_t rt_import_count;
extern const rt_named_addr rt_data_import_slots[], rt_exports[];
extern const uint32_t rt_data_import_slot_count, rt_export_count;
extern const uint32_t rt_func_addrs[], rt_func_count;
extern const rt_named_addr rt_data_symbols[];
extern const uint32_t rt_data_symbol_count;
uint32_t rt_data_symbol(const char *name);
extern const char *const rt_func_names[];
const char *rt_func_name(uint32_t addr, uint32_t *offset); /* the function containing a game address */
void rt_print_trace(cpu_t *c);                            /* the game call chain (checked builds) */

extern uint8_t *rt_mem; /* base of game memory */

/* memory */
int rt_mem_init(const char *image_path);
int rt_mem_init_from(const void *image, size_t size);
void rt_commit(uint32_t addr, uint32_t size);
uint32_t rt_malloc(uint32_t size);
uint32_t rt_calloc(uint32_t n, uint32_t size);
uint32_t rt_realloc(uint32_t addr, uint32_t size);
void rt_free(uint32_t addr);
uint32_t rt_malloc_usable(uint32_t addr);
uint32_t rt_strdup_guest(const char *s);           /* copy a host string into game memory */
uint32_t rt_static_string(const char *s);          /* same, interned (never freed) */

static inline void *G(uint32_t a) { return a ? rt_mem + a : NULL; }
static inline uint32_t rt_ld32(uint32_t a) { uint32_t v; memcpy(&v, rt_mem + a, 4); return v; }
static inline void rt_st32(uint32_t a, uint32_t v) { memcpy(rt_mem + a, &v, 4); }
static inline uint32_t rt_guest_addr(const void *p) { return p ? (uint32_t)((const uint8_t *)p - rt_mem) : 0; }

/* calling conventions (ARM softfp) */
uint32_t rt_arg(cpu_t *c, int k);                  /* k-th 32-bit argument word: r0-r3, then the stack */
double rt_darg(cpu_t *c, int k);                   /* a double in argument words k, k+1 */
float rt_farg(cpu_t *c, int k);
static inline void rt_ret(cpu_t *c, uint32_t v) { c->r[0] = v; }
void rt_dret(cpu_t *c, double v);
static inline void rt_fret(cpu_t *c, float v) { uint32_t u; memcpy(&u, &v, 4); c->r[0] = u; }

/* calls from the runtime into game code */
uint32_t rt_call(cpu_t *c, uint32_t fn, int nargs, ...);

/* host functions callable from game code */
typedef void (*rt_hostfn)(cpu_t *c, uint8_t *m);
uint32_t rt_hostfn_add(rt_hostfn fn, const char *name);
void rc_hostcall(cpu_t *c, uint8_t *m, uint32_t slot);
extern __thread uint32_t rt_current_hostfn;      /* game address of the host function being run */

/* threads */
cpu_t *rt_thread_cpu(void);                        /* the calling thread's CPU state (created on first use) */
void rt_threads_init(void);

/* imports */
void rt_imports_init(void);
typedef void (*rt_import_fn)(cpu_t *c);
void rt_import_register(const char *name, rt_import_fn fn);
void rt_libc_register(void);
void rt_pthread_register(void);
void rt_gl_register(void);
void rt_sles_register(void);
void rt_data_imports_init(void);
extern uint32_t rt_sl_iid[3];                      /* SL_IID_ENGINE, SL_IID_PLAY, SL_IID_BUFFERQUEUE (16-byte values) */

/* audio backend (audio_win.c, audio_android.c): a stream of 16-bit PCM that pulls its samples */
typedef void (*rt_audio_pull)(void *user, int16_t *out, int frames);
void *rt_audio_open(int rate, int channels, rt_audio_pull pull, void *user);
void rt_audio_start(void *stream);
void rt_audio_stop(void *stream);
void rt_audio_close(void *stream);

/* JNI */
uint32_t rt_jni_init(void);                        /* returns the game address of the JavaVM */
uint32_t rt_jni_env(void);                         /* the calling thread's JNIEnv (game address) */
uint32_t rt_jstring(const char *s);                /* a java.lang.String handle */
uint32_t rt_jni_class(const char *name);           /* a java.lang.Class handle */
void rt_jni_set_screen(int w, int h);
void rt_jni_set_paths(const char *obb, const char *data, const char *home, const char *temp);
extern void *(*rt_gl_getproc)(const char *name);   /* set by the platform layer before rt_imports_init */
uint32_t rt_export(const char *name);

/* paths: a game path starting with `from` is opened at `to` instead (the game's /data/data/<package> folder) */
void rt_path_alias(const char *from, const char *to);
const char *rt_host_path(const char *path); /* thread-local result */

/* the game (game.c) */
void rt_game_boot(const char *obb, const char *data, const char *home, const char *temp, int width, int height);
void rt_game_resize(int width, int height);
void rt_game_touch(int action, int x, int y, int pointer);
void rt_game_step(void);
void rt_game_pause(void);
void rt_game_resume(void);
cpu_t *rt_game_cpu(void);

/* diagnostics */
void rt_log(const char *fmt, ...);
void rt_fatal(const char *fmt, ...);
extern int rt_verbose;

/* guest printf/scanf (printf.c): format with arguments read from game memory */
typedef struct rt_args {
    cpu_t *c;
    int next;        /* next argument word for register/stack arguments */
    uint32_t va;     /* or: game address of an ARM va_list area (0 when unused) */
} rt_args;
uint32_t rt_args_u32(rt_args *a);
uint64_t rt_args_u64(rt_args *a);
double rt_args_double(rt_args *a);
int rt_vformat(char *out, size_t cap, const char *fmt, rt_args *a); /* returns the full length, like snprintf */
int rt_vscan(const char *in, const char *fmt, rt_args *a);

/* ---- libc stream (libc.c, net.c, wchar.c, printf.c): see docs/notes/libc.md ------------------------------ */
void rt_libc_set_data_dir(const char *dir);        /* host folder the game's /sdcard/gameloft/games/GloftR6HP maps to */
void rt_libc_add_data_prefix(const char *prefix);  /* one more guest path prefix that maps to the data folder */
int rt_map_path(const char *guest_path, char *out, size_t cap); /* aliases + data folder + case-insensitive fallback; 1 if the result exists */
void *rt_setjmp_prepare(cpu_t *c, uint32_t guest_jmp_buf); /* a host jmp_buf*: the lifter's setjmp macro, see libc.md */
void rt_signal_note(int sig, uint32_t target);     /* records a raise/pthread_kill */
int rt_vformat_w(uint32_t dst, uint32_t cap, uint32_t wfmt, rt_args *a); /* swprintf: wide format and output */

/* ---- JNI / game layer (jni.c, game.c): see docs/notes/jni.md ------------------------------------------------ */
uint32_t rt_jni_object(const char *cls);           /* a java.lang.Object handle of the given class (slash form) */
void rt_jni_set_locale(const char *tag);           /* "en", "fr", "de_DE", "zh-TW", ...: Game.GetPhoneLanguage and the nativeStart language; default env R6SV_LANG or "en" */
int rt_jni_game_language(void);                    /* the language index Game.d passes to nativeStart */
void rt_jni_set_device(const char *manufacturer, const char *model); /* lower-case Build.MANUFACTURER / MODEL (default "google" / "pixel") */
void rt_jni_set_igli(const void *data, uint32_t size); /* res/raw/igli.bin (262,144 bytes) for Game.db(); else files, see notes/jni.md */
void rt_game_accel(float x, float y, float z);     /* Game.nativeAccelerometer (the game ignores it) */
void rt_game_key(int keycode, int down);           /* Android key codes: Game.nativeSetOnKeyDown/Up (24, 25, 27 are filtered as in Java) */
void rt_game_restart_gl(int width, int height);    /* the GL context was recreated: GameRenderer.nativeStart again */
int rt_game_exit_requested(void);                  /* Game.Exit() was called */
/* host services behind Game.openBrowser / sendAppToBackground / Exit: weak defaults in jni.c (log, log, exit(0)) */
void rt_host_open_url(const char *url);
void rt_host_background(void);
void rt_host_exit(void);

#endif
