#!/usr/bin/env python3
"""Write what the runtime needs to load the original library into game memory.

  image.bin      the relocated image (IMAGE_BASE .. IMAGE_BASE + size), bss included as zeros
  image_meta.c   constants and tables: image base and size, .init_array, the import names by slot, the GOT slots of
                 the data imports, and the exported entry points the runtime calls (JNI_OnLoad, Java_*)

  py -3 tools/recomp/pack_image.py --so libNOVA3_neon.so --out build/runner
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from elftools.elf.descriptions import describe_reloc_type
from elftools.elf.relocation import RelocationSection

sys.path.insert(0, str(Path(__file__).parent))
from image import IMAGE_BASE, IMPORT_STUB_BASE, Image  # noqa: E402
from lift import entries  # noqa: E402

DATA_IMPORTS = {"__sF", "_ctype_", "_tolower_tab_", "__stack_chk_guard", "SL_IID_ENGINE", "SL_IID_PLAY",
                "SL_IID_BUFFERQUEUE"}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--so", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    image = Image(args.so)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "image.bin").write_bytes(bytes(image.memory))

    elf = image.elf
    dynsym = elf.get_section_by_name(".dynsym")
    got_slots = []  # (symbol, GOT slot game address) for data imports
    for sec in elf.iter_sections():
        if isinstance(sec, RelocationSection):
            for r in sec.iter_relocations():
                if describe_reloc_type(r["r_info_type"], elf) == "R_ARM_GLOB_DAT":
                    sym = dynsym.get_symbol(r["r_info_sym"])
                    if sym.name in DATA_IMPORTS:
                        got_slots.append((sym.name, IMAGE_BASE + r["r_offset"]))
    ia = elf.get_section_by_name(".init_array")
    init = [int.from_bytes(image.memory[ia["sh_addr"] + 4 * k:ia["sh_addr"] + 4 * k + 4], "little")
            for k in range(ia["sh_size"] // 4)]
    exports = sorted((s.name, IMAGE_BASE + (s["st_value"] & ~1)) for s in dynsym.iter_symbols()
                     if s["st_shndx"] != "SHN_UNDEF" and s["st_info"]["type"] == "STT_FUNC"
                     and (s.name.startswith("Java_") or s.name.startswith("JNI_")))

    out = ["/* Generated by tools/recomp/pack_image.py. */", '#include "rt.h"', "",
           f"const uint32_t rt_image_base = {IMAGE_BASE:#x}u;",
           f"const uint32_t rt_image_size = {image.size:#x}u;",
           f"const uint32_t rt_import_stub_base = {IMPORT_STUB_BASE:#x}u;",
           f"const uint32_t rt_init_array[] = {{ {', '.join(f'{a:#x}u' for a in init)} }};",
           f"const uint32_t rt_init_array_count = {len(init)};",
           f"const char *const rt_import_names[] = {{ {', '.join(f'\"{n}\"' for n in image.imports)} }};",
           f"const uint32_t rt_import_count = {len(image.imports)};",
           "const rt_named_addr rt_data_import_slots[] = {",
           *[f'  {{ "{n}", {a:#x}u }},' for n, a in got_slots],
           "};",
           f"const uint32_t rt_data_import_slot_count = {len(got_slots)};",
           "const rt_named_addr rt_exports[] = {",
           *[f'  {{ "{n}", {a:#x}u }},' for n, a in exports],
           "};",
           f"const uint32_t rt_export_count = {len(exports)};", ""]
    # data symbols the runtime sets up (the installer's licensing state, see runtime/host_main.c)
    wanted = ("lockPointer1", "lockPointer2", "lockPointer3", "lockPointer4", "isCheckLicence")
    symtab = elf.get_section_by_name(".symtab")
    data_syms = sorted((s.name, IMAGE_BASE + s["st_value"]) for s in symtab.iter_symbols() if s.name in wanted)
    out.append("const rt_named_addr rt_data_symbols[] = {")
    out += [f'  {{ "{n}", {a:#x}u }},' for n, a in data_syms]
    out.append("};")
    out.append(f"const uint32_t rt_data_symbol_count = {len(data_syms)};")
    # function names by address, for crash reports
    ents = sorted(entries(image).values(), key=lambda f: f.address)
    out.append("const uint32_t rt_func_addrs[] = {")
    out += [f"  {IMAGE_BASE + f.address:#x}u," for f in ents]
    out.append("};")
    out.append("const char *const rt_func_names[] = {")
    out += ['  "' + f.name.replace("\\", "\\\\").replace('"', '\\"') + '",' for f in ents]
    out.append("};")
    out.append(f"const uint32_t rt_func_count = {len(ents)};")
    (args.out / "image_meta.c").write_text("\n".join(out), encoding="utf-8")
    print(f"image {image.size:#x} bytes, {len(init)} constructors, {len(image.imports)} imports, "
          f"{len(got_slots)} data import slots, {len(exports)} exports")


if __name__ == "__main__":
    main()
