#!/usr/bin/env python3
"""Write what the runtime needs to load the original library into game memory.

  image.bin      the relocated image (IMAGE_BASE .. IMAGE_BASE + size), bss included as zeros
  image_meta.c   constants and tables: image base and size, .init_array, the import names by slot, the GOT slots of
                 the data imports, the exported entry points the runtime calls (JNI_OnLoad, Java_*, and the game
                 layer's appInit, appRender, notify*, ...) and the function names for crash reports

  py -3 tools/recomp/pack_image.py --so original/apk/lib/armeabi-v7a/librainbowsix.so --out build/runner

Works for a stripped library (only .dynsym) with Thumb code: every address in the tables is a game address with the
Thumb bit cleared, which is how the translated code's dispatcher names functions.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from elftools.elf.descriptions import describe_reloc_type
from elftools.elf.relocation import RelocationSection

sys.path.insert(0, str(Path(__file__).parent))
from image import IMAGE_BASE, IMPORT_STUB_BASE, Image  # noqa: E402
from lift import entries  # noqa: E402

# Data symbols the original library imports (STT_OBJECT, undefined) are found from the relocations; these OpenSL ES
# interface IDs are objects too in libraries that use OpenSL ES, so they are always recognised by name.
EXTRA_DATA_IMPORTS = {"SL_IID_ENGINE", "SL_IID_PLAY", "SL_IID_BUFFERQUEUE"}
# Exported C functions that are entry points of the game layer (besides Java_*/JNI_*): kept by prefix
ENTRY_PREFIXES = ("Java_", "JNI_", "app", "notify", "native", "GetNativeResource", "keyCode", "isBackKeyPressed")
# Symbols to look up in .symtab/.dynsym and publish as data (none for Rainbow Six: the library has no licence state)
DATA_SYMBOLS: tuple[str, ...] = ()


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--so", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    image = Image(args.so)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "image.bin").write_bytes(bytes(image.memory))

    elf = image.elf
    dynsym = elf.get_section_by_name(".dynsym")
    # GOT slots (game addresses) of the imported data objects; the runtime writes their addresses there
    got_slots = []
    for sec in elf.iter_sections():
        if isinstance(sec, RelocationSection):
            for r in sec.iter_relocations():
                if describe_reloc_type(r["r_info_type"], elf) not in ("R_ARM_GLOB_DAT", "R_ARM_ABS32"):
                    continue
                sym = dynsym.get_symbol(r["r_info_sym"])
                if sym.name and sym["st_shndx"] == "SHN_UNDEF" and (sym["st_info"]["type"] == "STT_OBJECT" or sym.name in EXTRA_DATA_IMPORTS):
                    got_slots.append((sym.name, IMAGE_BASE + r["r_offset"]))
    got_slots.sort()

    # constructors, with the Thumb bit cleared
    if getattr(image, "init_array", None):
        init = [IMAGE_BASE + (a[0] if isinstance(a, tuple) else a) for a in image.init_array]
    else:
        ia = elf.get_section_by_name(".init_array")
        init = [int.from_bytes(image.memory[ia["sh_addr"] + 4 * k:ia["sh_addr"] + 4 * k + 4], "little") & ~1
                for k in range(ia["sh_size"] // 4)] if ia is not None else []

    exports = {}
    for s in dynsym.iter_symbols():
        if s["st_shndx"] == "SHN_UNDEF" or s["st_info"]["type"] != "STT_FUNC" or not s.name or s.name.startswith("_Z"):
            continue
        if s.name.startswith(ENTRY_PREFIXES):
            exports[s.name] = IMAGE_BASE + (s["st_value"] & ~1)
    exports = sorted(exports.items())

    data_syms = []
    for secname in (".symtab", ".dynsym"):
        sec = elf.get_section_by_name(secname)
        if sec is not None:
            data_syms += [(s.name, IMAGE_BASE + s["st_value"]) for s in sec.iter_symbols()
                          if s.name in DATA_SYMBOLS and s["st_shndx"] != "SHN_UNDEF"]
    data_syms = sorted(set(data_syms))

    names = list(image.imports)  # import slot k <-> names[k] (IMPORT_STUB_BASE + 4k)
    out = ["/* Generated by tools/recomp/pack_image.py. */", '#include "rt.h"', "",
           f"const uint32_t rt_image_base = {IMAGE_BASE:#x}u;",
           f"const uint32_t rt_image_size = {image.size:#x}u;",
           f"const uint32_t rt_import_stub_base = {IMPORT_STUB_BASE:#x}u;",
           f"const uint32_t rt_init_array[] = {{ {', '.join(f'{a:#x}u' for a in init) or '0'} }};",
           f"const uint32_t rt_init_array_count = {len(init)};",
           f"const char *const rt_import_names[] = {{ {', '.join(c_str(n) for n in names) or '0'} }};",
           f"const uint32_t rt_import_count = {len(names)};",
           "const rt_named_addr rt_data_import_slots[] = {",
           *[f"  {{ {c_str(n)}, {a:#x}u }}," for n, a in got_slots], "  { 0, 0 }", "};",
           f"const uint32_t rt_data_import_slot_count = {len(got_slots)};",
           "const rt_named_addr rt_exports[] = {",
           *[f"  {{ {c_str(n)}, {a:#x}u }}," for n, a in exports], "  { 0, 0 }", "};",
           f"const uint32_t rt_export_count = {len(exports)};", "",
           "const rt_named_addr rt_data_symbols[] = {",
           *[f"  {{ {c_str(n)}, {a:#x}u }}," for n, a in data_syms], "  { 0, 0 }", "};",
           f"const uint32_t rt_data_symbol_count = {len(data_syms)};"]
    # function names by address, for crash reports (stripped functions are named sub_<address>)
    ents = sorted(entries(image).values(), key=lambda f: f.address)
    out.append("const uint32_t rt_func_addrs[] = {")
    out += [f"  {IMAGE_BASE + f.address:#x}u," for f in ents]
    out.append("  0xffffffffu")
    out.append("};")
    out.append("const char *const rt_func_names[] = {")
    out += [f"  {c_str(f.name)}," for f in ents]
    out.append('  "?"')
    out.append("};")
    out.append(f"const uint32_t rt_func_count = {len(ents)};")
    (args.out / "image_meta.c").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"image {image.size:#x} bytes, {len(init)} constructors, {len(names)} imports, "
          f"{len(got_slots)} data import slots ({', '.join(n for n, _ in got_slots)}), {len(exports)} exports, "
          f"{len(ents)} functions")


if __name__ == "__main__":
    main()
