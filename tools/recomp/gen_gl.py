CTYPE = {"e": "uint32_t", "u": "uint32_t", "i": "int32_t", "z": "int32_t", "x": "uint32_t", "b": "uint8_t",
         "n": "intptr_t", "f": "float", "p": "void *", "s": "const char *", "S": "const char *const *",
         "A": "const void *", "I": "const void *"}
RTYPE = {"v": "void", "e": "uint32_t", "u": "uint32_t", "i": "int32_t", "b": "uint8_t", "s": "const char *",
         "p": "void *"}


def arg_expr(code, k):
    w = f"rt_arg(c, {k})"
    return {"e": w, "u": w, "x": w, "i": f"(int32_t){w}", "z": f"(int32_t){w}", "b": f"(uint8_t){w}",
            "n": f"(intptr_t)(int32_t){w}", "f": f"rt_farg(c, {k})", "p": f"G({w})", "s": f"(const char *)G({w})",
            "A": f"(array_buffer ? (const void *)(uintptr_t){w} : G({w}))",
            "I": f"(element_buffer ? (const void *)(uintptr_t){w} : G({w}))"}[code]


def main():
    funcs = [line.split() for line in GL.strip().splitlines()]
    out = ['/* Generated by tools/recomp/gen_gl.py: OpenGL ES 2 imports. Do not edit by hand. */',
           '#include <stdlib.h>', '#include <string.h>', '#include "rt.h"', '',
           '#ifdef _WIN32', '#define GLAPI __stdcall', '#else', '#define GLAPI', '#endif', '',
           'static uint32_t array_buffer, element_buffer;', 'static void missing(const char *name);', '']
    for name, ret, args in funcs:
        args = "" if args == "-" else args
        params = ", ".join(CTYPE[a] for a in args) or "void"
        out.append(f"static {RTYPE[ret]} (GLAPI *p_{name})({params});")
    out.append("static void (GLAPI *p_glGetBufferParameteriv)(uint32_t, uint32_t, int32_t *);")
    out.append("static void (GLAPI *p_glMapBufferOES)(void);  /* not used: mapping is emulated */")
    out.append("")
    special = {"glBindBuffer", "glGetString", "glShaderSource"}
    for name, ret, args in funcs:
        args = "" if args == "-" else args
        if name in special:
            continue
        call_args = ", ".join(arg_expr(a, k) for k, a in enumerate(args))
        guard = f"if (!p_{name}) {{ missing(\"{name}\"); {'rt_ret(c, 0); ' if ret != 'v' else ''}return; }} "
        if ret == "v":
            body = f"p_{name}({call_args});"
        else:
            body = f"rt_ret(c, (uint32_t)p_{name}({call_args}));"
        out.append(f"static void imp_{name}(cpu_t *c) {{ {guard}{body} }}")
    out += [
        "",
        "static void missing(const char *name) {",
        "    static const char *seen[64];",
        "    for (int k = 0; k < 64; k++) { if (seen[k] == name) return; if (!seen[k]) { seen[k] = name; break; } }",
        '    rt_log("GL: %s is not available on this host (call ignored)", name);',
        "}",
        "",
        "static void imp_glBindBuffer(cpu_t *c) {",
        "    uint32_t target = rt_arg(c, 0), buf = rt_arg(c, 1);",
        "    if (target == 0x8892) array_buffer = buf;",
        "    if (target == 0x8893) element_buffer = buf;",
        "    p_glBindBuffer(target, buf);",
        "}",
        "static void imp_glGetString(cpu_t *c) {",
        "    const char *s = p_glGetString(rt_arg(c, 0));",
        "    rt_ret(c, s ? rt_static_string(s) : 0);",
        "}",
        "static void imp_glShaderSource(cpu_t *c) {",
        "    int32_t n = (int32_t)rt_arg(c, 1);",
        "    uint32_t strings = rt_arg(c, 2), lengths = rt_arg(c, 3);",
        "    const char **v = malloc(sizeof(char *) * (size_t)(n > 0 ? n : 1));",
        "    for (int32_t k = 0; k < n; k++) v[k] = (const char *)G(rt_ld32(strings + 4 * (uint32_t)k));",
        "    p_glShaderSource(rt_arg(c, 0), n, v, G(lengths));",
        "    free(v);",
        "}",
        "",
        "/* glMapBufferOES: a shadow block in game memory, uploaded by glUnmapBufferOES */",
        "static struct { uint32_t target, buffer, addr, size; } maps[4];",
        "static void imp_glMapBufferOES(cpu_t *c) {",
        "    uint32_t target = rt_arg(c, 0), buffer = target == 0x8893 ? element_buffer : array_buffer;",
        "    int32_t size = 0;",
        "    p_glGetBufferParameteriv(target, 0x8764 /* GL_BUFFER_SIZE */, &size);",
        "    for (int k = 0; k < 4; k++)",
        "        if (!maps[k].addr) {",
        "            maps[k].target = target; maps[k].buffer = buffer; maps[k].size = (uint32_t)size;",
        "            maps[k].addr = rt_calloc(1, (uint32_t)(size > 0 ? size : 1));",
        "            rt_ret(c, maps[k].addr);",
        "            return;",
        "        }",
        "    rt_ret(c, 0);",
        "}",
        "static void imp_glUnmapBufferOES(cpu_t *c) {",
        "    uint32_t target = rt_arg(c, 0);",
        "    for (int k = 0; k < 4; k++)",
        "        if (maps[k].addr && maps[k].target == target) {",
        "            p_glBufferSubData(target, 0, (intptr_t)maps[k].size, G(maps[k].addr));",
        "            rt_free(maps[k].addr);",
        "            maps[k].addr = 0;",
        "        }",
        "    rt_ret(c, 1);",
        "}",
        "",
        "void *(*rt_gl_getproc)(const char *name);",
        "",
        "void rt_gl_register(void) {",
        "    if (!rt_gl_getproc) rt_fatal(\"rt_gl_getproc is not set\");",
    ]
    for name, ret, args in funcs:
        if name in ("glMapBufferOES", "glUnmapBufferOES"):
            continue
        out.append(f'    *(void **)&p_{name} = rt_gl_getproc("{name}");')
    out.append('    *(void **)&p_glGetBufferParameteriv = rt_gl_getproc("glGetBufferParameteriv");')
    for name, ret, args in funcs:
        out.append(f'    rt_import_register("{name}", (rt_import_fn)imp_{name});')
    out.append('    rt_import_register("glMapBufferOES", (rt_import_fn)imp_glMapBufferOES);')
    out.append('    rt_import_register("glUnmapBufferOES", (rt_import_fn)imp_glUnmapBufferOES);')
    out.append("    (void)p_glMapBufferOES;")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
